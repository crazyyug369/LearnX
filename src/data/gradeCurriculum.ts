/**
 * Helper to normalize grade name (e.g. "Grade 10" -> "Class 10", "10" -> "Class 10")
 */
export function normalizeGradeName(grade?: string): string {
  if (!grade) return 'Class 10';
  const g = grade.trim().toLowerCase();
  if (g.includes('6')) return 'Class 6';
  if (g.includes('7')) return 'Class 7';
  if (g.includes('8')) return 'Class 8';
  if (g.includes('9')) return 'Class 9';
  if (g.includes('11')) return 'Class 11';
  if (g.includes('12')) return 'Class 12';
  return 'Class 10';
}

/**
 * Retrieve curriculum map for a specific grade.
 */
export function getCurriculumForGrade(grade?: string, subject?: string): Record<string, ConceptNode[]> {
  const norm = normalizeGradeName(grade);
  const gradeMap = GRADE_CURRICULUM_DATA[norm] || GRADE_CURRICULUM_DATA['Class 10'];

  if (subject && gradeMap[subject]) {
    return { [subject]: JSON.parse(JSON.stringify(gradeMap[subject])) };
  }
  return JSON.parse(JSON.stringify(gradeMap));
}

/**
 * Retrieve diagnostic questions for a specific grade, covering Easy, Medium, Hard tiers.
 */
export function getDiagnosticQuestionsForGrade(grade?: string, subject?: string): DiagnosticQuestion[] {
  const norm = normalizeGradeName(grade);
  const questions = GRADE_DIAGNOSTIC_QUESTIONS[norm] || GRADE_DIAGNOSTIC_QUESTIONS['Class 10'];

  if (subject) {
    const filtered = questions.filter((q) => {
      const cur = (GRADE_CURRICULUM_DATA[norm] || {})[subject] || [];
      return cur.some((c) => c.id === q.conceptId);
    });
    if (filtered.length > 0) return filtered;
  }
  return questions;
}
